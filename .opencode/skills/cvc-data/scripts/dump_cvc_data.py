#!/usr/bin/env python3
"""Decode STCS application data binary files back into a Markdown report, driven by a
configuration template. Inverse of gen_cvc_data.py.

WHAT IT READS
    One or more files produced by the STCS config-data protocol (as generated by
    gen_cvc_data.py, or any tool emitting the same layout):
        ASW1.bin        (DP    file, magic 0xABABABAB)
        Config2.line1   (LINE  file, magic 0xACACACAC)
        Config1.train   (TRAIN file, magic 0xADADADAD)
    Single files with the full TLV framing are expected; the concatenated stream and
    its 8-byte version tail (dp_version + project_version) are NOT decoded here — the
    files themselves carry no version bytes (the stream assembler appends them).

WIRE FORMAT (matches the INIT config-data parsing protocol, all big-endian)
    file = magic:4 | file_length:4 | field_1 | field_2 | ... | crc:4
    field_n = symbol:4 (template ASW @SYMBOL, ATP 0x66AA5599, SDMU 0xA5A59696) |
              field_length:4 | body:field_length
    file_length counts all fields + crc; CRC is computed over magic+len+all fields
    (i.e. the whole file minus its last 4 bytes) as CRC-32/ISO-HDLC (zlib.crc32).
    Fields are parsed sequentially; each is decoded with the template whose ASW SYMBOL
    matches. A field with no matching template is reported as not decoded (warning).

WHAT IT OUTPUTS
    Markdown only (no plain-text mode). Per file a heading, a file status line, then
    per field a sub-heading, a status line and one table row per template field:
        ## path
        DIST=x magic=0x... crc=OK|BAD file=NB fields=[0x66AA5599=NB, ...] [unaccounted=NB]
        ### ATP (0x66AA5599)
        field=ATP symbol=0x... body=NB walk=OK|OK+NB-unaccounted|INCOMPLETE(...)
        | offset | len | field name | value(hex) | value(dec) | flags |
    Offsets are relative to each field body. flags carries OUT-OF-RANGE(min..max) /
    EXTRA-SLOT. Trailing unconsumed body bytes are noted in a blockquote.
    Repeated groups are expanded by the data's count byte, exactly like the parser:
        - ISREPEAT wrappers: N_ITEM leaf, then the REPEAT block's leaves n times,
          indexed " [k]".
        - Pinned wrappers (N_ITEM + explicit "(i)" entries): n entries are read;
          values beyond the template's entries are marked EXTRA-SLOT, and a warning
          fires when n != the number of template entries.

MISMATCH / INTEGRITY DETECTION (never aborts the batch; warnings also on stderr)
    CRC MISMATCH                    stored CRC != computed CRC-32 of the covered range
    TEMPLATE/DATA MISMATCH (more)   template walk exhausted the body: fields decoded
                                    before the failure are still reported; the two were
                                    built from different template versions
    TEMPLATE/DATA MISMATCH (extra)  template consumed fewer bytes than the body holds:
                                    values after the divergence point are likely
                                    byte-shifted; trailing count is reported
    OUT-OF-RANGE                    decoded value outside the template MINVALUE/MAXVALUE
    no template for field           field symbol not covered by any -t template
    unknown magic / no field / length overrun / unreadable file: per-file
    ERROR line, remaining files continue

USAGE
    python scripts/dump_cvc_data.py FILE [FILE ...] [options]

      -t, --template PATH   template XML (required, repeatable: one per field, e.g.
                            -t ATPCfgTemplate.xml -t SDMUCfgTemplate.xml)
      -o, --out PATH        write the Markdown report to PATH (default: stdout)
          --values-out PATH additionally write a gen_cvc_data.py --values JSON file
                        captured from the decoded data, GROUPED by class then field:
                            {"DP": {"ATP": {...}, "SDMU": {...}}, "LINE": {...}, ...}
                        each field by exact template name, REPEAT groups ("NAME [k]"
                        rows) as lists. Feed it back:
                            gen_cvc_data.py -t <same templates, any order> --values <this file>
                        to regenerate byte-identical files.
                        This grouped form is the only form gen_cvc_data.py accepts.
                        Fields whose template walk failed are excluded (partial data
                        can't round-trip); EXTRA-SLOT rows have no template name and
                        are skipped with a warning.
      -h, --help            full flag help

    Examples:
      # one file -> report to stdout
      python scripts/dump_cvc_data.py -t ATP.xml -t SDMU.xml Config1.train

      # full set -> one Markdown report
      python scripts/dump_cvc_data.py -t ATP.xml -t SDMU.xml ASW1.bin Config2.line1 Config1.train -o decoded_report.md

      # capture data as a values file, regenerate it byte-identically
      python scripts/dump_cvc_data.py -t ATP.xml -t SDMU.xml --values-out captured.json ASW1.bin Config2.line1 Config1.train
      python scripts/gen_cvc_data.py   -t ATP.xml -t SDMU.xml --values captured.json -o regen/

    Exit codes: 0 on success (mismatch warnings do not change this); 1 on container
    errors (file unreadable, unknown magic, no field, length overrun).
"""

import argparse
import io
import json
import re
import struct
import sys
import zlib
import xml.etree.ElementTree as ET
from pathlib import Path

MAGIC_DIST = {0xABABABAB: "DP", 0xACACACAC: "LINE", 0xADADADAD: "TRAIN"}


def ensure_utf8_stdio():
    """Force stdout/stderr to UTF-8.

    Windows defaults to the system code page (cp936/GBK on Chinese installs), where some
    characters used in reports raise UnicodeEncodeError. Skipped when already UTF-8 or
    when the stream has no reconfigure() (replaced by an IDE or test framework).
    """
    for name in ("stdout", "stderr"):
        stream = getattr(sys, name, None)
        if stream is None:
            continue
        encoding = (getattr(stream, "encoding", "") or "").replace("-", "").lower()
        if encoding == "utf8":
            continue
        reconfigure = getattr(stream, "reconfigure", None)
        if reconfigure is None:
            continue
        try:
            reconfigure(encoding="utf-8", errors="replace")
        except (ValueError, OSError):
            pass


class DecodeError(Exception):
    pass


def to_int(text):
    if text is None:
        return None
    text = text.strip()
    if not text:
        return None
    return int(text, 16) if text.lower().startswith("0x") else int(text)


class Reader:
    """Bounds-checked big-endian cursor over the ATP body."""

    def __init__(self, body, base_offset=0):
        self.body = body
        self.pos = 0
        self.base_offset = base_offset

    @property
    def offset(self):
        return self.base_offset + self.pos

    @property
    def remaining(self):
        return len(self.body) - self.pos

    def peek(self, size):
        if self.pos + size > len(self.body):
            return None
        return self.body[self.pos:self.pos + size]

    def read(self, size):
        if self.pos + size > len(self.body):
            raise DecodeError("body exhausted at offset %d, wanted %d byte(s)"
                              % (self.offset, size))
        value = int.from_bytes(self.body[self.pos:self.pos + size], "big")
        self.pos += size
        return value

    def read_reader(self, size):
        if self.pos + size > len(self.body):
            raise DecodeError("body exhausted at offset %d, wanted %d byte(s)"
                              % (self.offset, size))
        child = Reader(self.body[self.pos:self.pos + size], self.offset)
        self.pos += size
        return child


def leaf_record(param, reader, warn, index_note=""):
    name = param.get("NAME")
    size = int(param.get("SIZE"))
    offset = reader.offset
    value = reader.read(size)
    if index_note and name.endswith("([k])"):
        name = name[:-5]  # template carries the ([k]) marker; the " [k]" index replaces it
    rec = {
        "offset": offset,
        "size": size,
        "name": name + (index_note or ""),
        "value": value,
    }
    lo, hi = to_int(param.get("MINVALUE")), to_int(param.get("MAXVALUE"))
    if lo is not None and value < lo or hi is not None and value > hi:
        rec["out_of_range"] = (lo, hi)
        warn("%s@%d: value %s outside template range [%s..%s]"
             % (name, offset, value, lo, hi))
    return rec


def walk_wrapper_contents(wrapper, children, reader, out, warn):
    if not children:
        out.append(leaf_record(wrapper, reader, warn))
        return

    repeat = wrapper.find("REPEAT")
    param_children = [c for c in children if c.tag == "PARAM"]

    if repeat is not None:
        # ISREPEAT: N_ITEM leaf then REPEAT block x n
        first = param_children[0]
        out.append(leaf_record(first, reader, warn))
        n = out[-1]["value"]
        for k in range(n):
            for rp in repeat.findall("PARAM"):
                out.append(leaf_record(rp, reader, warn, index_note=" [%d]" % k))
        return

    # Pinned array: N_ITEM + explicit "(i)" entries
    if len(param_children) > 1 and (param_children[0].get("NAME") or "").startswith("N_ITEM"):
        first = param_children[0]
        out.append(leaf_record(first, reader, warn))
        n = out[-1]["value"]
        explicit = param_children[1:]
        if n != len(explicit):
            warn("%s: count %d != %d template entries; decoding %d slot(s)"
                 % (wrapper.get("NAME"), n, len(explicit), max(n, len(explicit))))
        slots = explicit if n >= len(explicit) else explicit[:n]
        for idx, c in enumerate(slots):
            out.append(leaf_record(c, reader, warn))
        if n > len(explicit):
            for idx in range(len(explicit), n):
                size = int(explicit[0].get("SIZE")) if explicit else 2
                offset = reader.offset
                value = reader.read(size)
                out.append({"offset": offset, "size": size,
                            "name": "%s(%d)" % (re.sub(r"\(\d+\)$", "", explicit[0].get("NAME") or "?", ), idx + 1),
                            "value": value, "hex": False, "extra_slot": True})
        return

    for c in param_children:
        walk_wrapper(c, reader, out, warn)


def walk_wrapper(wrapper, reader, out, warn):
    children = [c for c in wrapper if c.tag in ("PARAM", "REPEAT")]
    symbol_text = wrapper.get("SYMBOL")
    if symbol_text:
        symbol = int(symbol_text, 16)
        optional = wrapper.get("ISOPTIONAL", "").lower() == "true"
        header = reader.peek(4)
        if header is None or int.from_bytes(header, "big") != symbol:
            if optional:
                return
            raise DecodeError("%s: expected nested-field symbol 0x%08X at offset %d"
                              % (wrapper.get("NAME"), symbol, reader.offset))

        reader.read(4)
        length = reader.read(4)
        expected_length = to_int(wrapper.get("LENGTH"))
        if expected_length is not None and length != expected_length:
            warn("%s@%d: wrapper length %d differs from template LENGTH %d"
                 % (wrapper.get("NAME"), reader.offset - 8, length, expected_length))
        nested_reader = reader.read_reader(length)
        walk_wrapper_contents(wrapper, children, nested_reader, out, warn)
        if nested_reader.remaining:
            warn("%s: wrapper payload has %d byte(s) unaccounted at offset %d"
                 % (wrapper.get("NAME"), nested_reader.remaining, nested_reader.offset))
        return

    walk_wrapper_contents(wrapper, children, reader, out, warn)


def decode_class(paramclass, body, warn):
    """Walk the template over the body. Never raises: template/data mismatches are
    reported as warnings and partial records are still returned."""
    reader = Reader(body)
    out = []
    walk_error = None
    try:
        for param in paramclass.findall("PARAM"):
            walk_wrapper(param, reader, out, warn)
    except DecodeError as e:
        walk_error = str(e)

    trailing = len(body) - reader.pos
    if walk_error:
        warn("TEMPLATE/DATA MISMATCH: template needs more bytes than the data provides "
             "(%s) — decoded %d field(s) before failing; the two were built from different "
             "template versions" % (walk_error, len(out)))
    elif trailing:
        warn("TEMPLATE/DATA MISMATCH: template consumed %d of %d body byte(s), %d unaccounted "
             "— decoded values after the divergence point may be byte-shifted; the two were "
             "built from different template versions" % (reader.pos, len(body), trailing))
    return out, trailing, walk_error


def frame_split(data, warn):
    """Validate one file TLV, return (dist, magic, crc_ok, fields, trailing) where
    fields = [(symbol, body)] parsed sequentially after the 8-byte file header."""
    if len(data) < 16:
        raise DecodeError("file too short for file TLV (%d bytes)" % len(data))
    magic, file_length = struct.unpack(">II", data[:8])
    dist = MAGIC_DIST.get(magic)
    if dist is None:
        raise DecodeError("unknown file magic 0x%08X (expected ABABABAB/ACACACAC/ADADADAD)" % magic)
    if 8 + file_length > len(data):
        raise DecodeError("declared file_length %d overruns %d-byte file" % (file_length, len(data)))
    region = data[8:8 + file_length]
    stored_crc = struct.unpack(">I", region[-4:])[0]
    calc = zlib.crc32(data[:8 + file_length - 4]) & 0xFFFFFFFF
    crc_ok = (stored_crc == calc)
    if not crc_ok:
        warn("CRC MISMATCH: stored 0x%08X != computed 0x%08X" % (stored_crc, calc))

    payload = region[:-4]
    fields, pos = [], 0
    while pos + 8 <= len(payload):
        symbol, length = struct.unpack(">II", payload[pos:pos + 8])
        if pos + 8 + length > len(payload):
            warn("field 0x%08X at offset %d declares %d byte(s), only %d remain before CRC"
                 % (symbol, 8 + pos, length, len(payload) - pos - 8))
            break
        fields.append((symbol, payload[pos + 8:pos + 8 + length]))
        pos += 8 + length
    trailing = len(payload) - pos
    if not fields:
        raise DecodeError("no application field found after file header")
    if trailing:
        warn("%d byte(s) between last field end and CRC not covered by any field" % trailing)
    return dist, magic, crc_ok, fields, trailing


def _fmt_hex(value):
    return "0x%X" % value


def _cell_flags(r):
    flags = []
    if r.get("out_of_range"):
        flags.append("OUT-OF-RANGE [%s..%s]" % r["out_of_range"])
    if r.get("extra_slot"):
        flags.append("EXTRA-SLOT")
    return ", ".join(flags)


def render_markdown(records, trailing, title, meta, out_file):
    out_file.write("### %s\n\n%s\n\n" % (title, meta))
    cols = ["offset", "len", "field name", "value(hex)", "value(dec)", "flags"]
    align = ["---:", "---:", ":---", "---:", "---:", ":---"]
    out_file.write("| " + " | ".join(cols) + " |\n")
    out_file.write("| " + " | ".join(align) + " |\n")
    for r in records:
        row = ["%d" % r["offset"], "%d" % r["size"], r["name"],
               _fmt_hex(r["value"]), "%d" % r["value"], _cell_flags(r)]
        out_file.write("| " + " | ".join(row) + " |\n")
    if trailing:
        out_file.write("\n> **template/data note:** %d trailing byte(s) in field body not "
                       "consumed by template walk\n" % trailing)


def main(argv=None):
    ensure_utf8_stdio()
    ap = argparse.ArgumentParser(
        description="Decode STCS application data binary files into a Markdown report driven by a template XML",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="examples:\n"
               "  python scripts/dump_cvc_data.py -t my_template.xml Config1.train\n"
               "  python scripts/dump_cvc_data.py -t my_template.xml -o report.md ASW1.bin Config2.line1 Config1.train\n"
               "  python scripts/dump_cvc_data.py -t my_template.xml --values-out captured.json Config1.train")
    ap.add_argument("files", nargs="+", help="data file(s): ASW1.bin / Config2.line1 / Config1.train (any location/name)")
    ap.add_argument("-t", "--template", required=True, action="append",
                    help="template XML used to decode (any name/location); repeat for each "
                         "application field, e.g. -t ATP.xml -t SDMU.xml (gen_cvc_data.py "
                         "requires both, in any order). Fields are matched to "
                         "templates by ASW SYMBOL, not by order.")
    ap.add_argument("-o", "--out", help="write report to this file (default stdout)")
    ap.add_argument("--values-out", metavar="PATH",
                    help="also write a gen_cvc_data.py --values JSON captured from the decoded "
                         "data, grouped by class then field: {\"DP\": {\"ATP\": {...}, \"SDMU\": {...}}, ...}")
    args = ap.parse_args(argv)

    # symbol -> (function, {DIST: PARAMCLASS})
    templates = {}
    for tpath in args.template:
        asw = ET.parse(tpath).getroot().find(".//ASW")
        if asw is None or not asw.get("SYMBOL"):
            print("warning: %s: no <ASW SYMBOL=...> element; skipped" % tpath, file=sys.stderr)
            continue
        symbol = int(asw.get("SYMBOL"), 16)
        if symbol in templates:
            raise DecodeError("%s: ASW SYMBOL 0x%08X already defined by another template" % (tpath, symbol))
        templates[symbol] = (asw.get("FUNCTION") or "0x%08X" % symbol,
                             {pc.get("DIST"): pc for pc in asw.iter("PARAMCLASS")})
    if not templates:
        raise DecodeError("no template with an <ASW SYMBOL=...> element was given")

    warn_msgs = []
    def warn(m):
        warn_msgs.append(m)
        print("warning: %s" % m, file=sys.stderr)

    report_text = io.StringIO()
    decoded = []

    for path in args.files:
        try:
            data = Path(path).read_bytes()
            dist, magic, crc_ok, fields, trailing_bytes = frame_split(data, warn)
        except (DecodeError, OSError) as e:
            print("error: %s: %s" % (path, e), file=sys.stderr)
            report_text.write("## %s\n\nERROR: %s\n\n" % (path, e))
            continue
        sizes = ", ".join("0x%08X=%dB" % (s, len(b)) for s, b in fields)
        meta = "DIST=%s magic=0x%08X crc=%s file=%dB fields=[%s]%s" % (
            dist, magic, "OK" if crc_ok else "BAD", len(data), sizes,
            " unaccounted=%dB" % trailing_bytes if trailing_bytes else "")
        report_text.write("## %s\n\n%s\n\n" % (path, meta))
        for symbol, body in fields:
            tpl = templates.get(symbol)
            if tpl is None or dist not in tpl[1]:
                warn("%s: no template for field 0x%08X (DIST=%s, %d byte(s)); not decoded"
                     % (path, symbol, dist, len(body)))
                report_text.write("### 0x%08X\n\nno template given; %d byte(s) not decoded\n\n"
                                  % (symbol, len(body)))
                continue
            function, classes = tpl
            fwarn = lambda m, f=function: warn("[%s] %s" % (f, m))
            records, trailing, walk_error = decode_class(classes[dist], body, fwarn)
            status = "walk=OK"
            if walk_error:
                status = "walk=INCOMPLETE(template-needs-more)"
            elif trailing:
                status = "walk=OK+%dB-unaccounted" % trailing
            render_markdown(records, trailing, "%s (0x%08X)" % (function, symbol),
                            "field=%s symbol=0x%08X body=%dB %s" % (function, symbol, len(body), status),
                            report_text)
            decoded.append((path, dist, function, records, walk_error))

    if args.values_out:
        # grouped by DIST class then field: {"DP": {"ATP": {...}, "SDMU": {...}}, ...}
        per_class = {}
        for path, dist, function, records, walk_error in decoded:
            if walk_error:
                warn("values-out: excluded %s [%s] (template walk incomplete: %s)" % (path, function, walk_error))
                continue
            slot = per_class.setdefault((dist, function), {"scalars": {}, "groups": {}})
            for r in records:
                if r.get("extra_slot"):
                    warn("values-out: skipped %r in %s (no template name to regenerate)"
                         % (r["name"], path))
                    continue
                m = re.match(r"^(.*?) \[(\d+)\]$", r["name"])
                if m:
                    slot["groups"].setdefault(m.group(1), []).append((int(m.group(2)), r["value"]))
                else:
                    if r["name"] in slot["scalars"] and slot["scalars"][r["name"]] != r["value"]:
                        warn("values-out: %s %r present in several files with DIFFERENT values "
                             "— kept %s, ignored %s"
                             % (dist, r["name"], slot["scalars"][r["name"]], r["value"]))
                    else:
                        slot["scalars"][r["name"]] = r["value"]
        doc = {}
        for (dist, function), slot in per_class.items():
            entry = dict(slot["scalars"])
            for base, items in sorted(slot["groups"].items()):
                items.sort()
                if [i for i, _ in items] != list(range(len(items))):
                    warn("values-out: group %r has non-contiguous indices; skipped" % base)
                    continue
                new_list = [v for _, v in items]
                if base in entry and entry[base] != new_list:
                    warn("values-out: %s %r group %r differs across files — kept first" % (dist, function, base))
                else:
                    entry[base] = new_list
            doc.setdefault(dist, {})[function] = entry
        doc = {d: doc[d] for d in ("DP", "LINE", "TRAIN") if d in doc}
        Path(args.values_out).write_text(json.dumps(doc, indent=2) + "\n", encoding="utf-8")
        print("values written: %s (%s)" % (args.values_out,
              ", ".join("%s/%s: %d keys" % (d, f, len(v)) for d in doc for f, v in doc[d].items())))

    payload = report_text.getvalue()
    if args.out:
        Path(args.out).write_text(payload, encoding="utf-8")
        print("report written: %s" % args.out)
    else:
        print(payload)
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except DecodeError as e:
        print("error: %s" % e, file=sys.stderr)
        sys.exit(1)
